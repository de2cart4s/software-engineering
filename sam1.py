# Импорт модуля datetime для работы с датой и временем
from datetime import datetime
# Импорт функции sqrt из модуля math для вычисления квадратного корня
from math import sqrt

# Определение функции main с произвольным количеством именованных аргументов
def main(**kwargs):
    # Итерация по элементам словаря (ключ и значение)
    for key in kwargs.items():
        # Вычисление длины вектора по его координатам (теорема Пифагора)
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)
        # Вывод результата в консоль
        print(result)

# Проверка, что скрипт запущен напрямую
if __name__ == '__main__':
    # Запись времени начала выполнения программы
    start_time = datetime.now()
    # Вызов функции main с передачей аргументов
    main(
        one=[10, 3],
        two=[5, 4],
        three=[15, 13],
        four=[93, 53],
        five=[133, 15]
    )
    # Расчет времени выполнения
    time_costs = datetime.now() - start_time
    # Вывод времени выполнения
    print(f"Время выполнения программы - {time_costs}")